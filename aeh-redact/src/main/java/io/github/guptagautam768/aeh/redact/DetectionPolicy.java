package io.github.guptagautam768.aeh.redact;

/** What to do when a secret or PII value is detected at record time (RD-009, SEC-007). */
public enum DetectionPolicy {
  /** Replace, continue, and record counts. This is the default. */
  REDACT,
  /** Abort the case. Nothing is written. */
  FAIL
}
